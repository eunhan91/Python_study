# 키패드 알파벳-숫자 매핑 (대문자 기준)
keypad = {
    'A': 2, 'B': 2, 'C': 2, 'D': 3, 'E': 3, 'F': 3,
    'G': 4, 'H': 4, 'I': 4, 'J': 5, 'K': 5, 'L': 5,
    'M': 6, 'N': 6, 'O': 6, 'P': 7, 'Q': 7, 'R': 7, 'S': 7,
    'T': 8, 'U': 8, 'V': 8, 'W': 9, 'X': 9, 'Y': 9, 'Z': 9
}

word = input("문자열을 입력하시오: ")

for ch in word:
    # 입력된 문자가 딕셔너리에 존재하는지 확인
    if ch in keypad:
        # 해당하는 숫자를 라인브레이킹 없이 이어서 출력
        print(keypad[ch], end="")
        
print() # 마지막 라인브레이킹 처리